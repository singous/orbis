import { expect, test, type Page, type APIRequestContext } from "@playwright/test";
import { ownerSession, createCollection, openWithSession, responseData, workspacePath, sessionHeaders } from "../helpers/api-fixtures";

async function seed(page: Page, request: APIRequestContext) {
  const session = await ownerSession(request);
  const collection = await createCollection(request, session, "Grid interactions " + Date.now());
  const headers = sessionHeaders(session);
  const sheet = await responseData(await request.post(workspacePath(session, "/sheets"), { headers, data: { id: crypto.randomUUID(), collection_id: collection.id, title: "表格交互验收", template: "" } }));
  const text = sheet.definition.fields[0];
  for (const value of ["Alpha", "Beta", "Gamma"]) await responseData(await request.post(workspacePath(session, `/sheets/${sheet.id}/changes`), { headers, data: { operation_id: crypto.randomUUID(), schema_version: sheet.schema_version, records: [{ id: crypto.randomUUID(), version: 0, values: { [text.id]: value } }] } }));
  await openWithSession(page, session, `/documents/${sheet.document_id}`);
  const grid = page.getByRole("grid", { name: "数据表", exact: true });
  await expect(grid.getByRole("gridcell").first()).toHaveText("Alpha");
  const records = async () => (await responseData(await request.get(workspacePath(session, `/sheets/${sheet.id}/records`), { headers }))).items;
  return { grid, text, sheet, records };
}
async function drag(page: Page, handle: ReturnType<Page["locator"]>, target: ReturnType<Page["locator"]>, after = false) {
  const from = (await handle.boundingBox())!, to = (await target.boundingBox())!;
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2);
  await page.mouse.down();
  await page.mouse.move(to.x + to.width / 2, to.y + to.height * (after ? .8 : .2), { steps: 10 });
  await page.mouse.up();
}

test("field manager reorders, hides and restores columns; header menu works through both triggers", async ({ page, request }) => {
  const { grid, sheet } = await seed(page, request);
  const names = sheet.definition.fields.map((field: { name: string }) => field.name);
  await expect(page.locator(".sheet-toolbar")).toHaveCSS("background-color", "rgb(250, 250, 250)");
  await expect(page.getByRole("button", { name: "生成表单", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "字段管理", exact: true }).click();
  const manager = page.getByRole("dialog", { name: "字段管理", exact: true });
  await drag(page, manager.getByRole("button", { name: `拖拽排序${names[2]}` }), manager.locator(".sheet-managed-field").first());
  await manager.getByRole("button", { name: "应用", exact: true }).click();
  await expect(grid.getByRole("columnheader").first()).toContainText(names[2]);
  await page.getByRole("button", { name: "字段管理", exact: true }).click();
  await manager.getByRole("checkbox", { name: names[1], exact: true }).uncheck();
  await expect(manager.getByRole("checkbox", { name: names[1], exact: true })).not.toBeChecked();
  const saveRequest = page.waitForRequest(request => request.method() === "PUT" && request.url().endsWith(`/sheets/${sheet.id}`));
  await manager.getByRole("button", { name: "应用", exact: true }).click();
  expect((await saveRequest).postDataJSON().definition.views[0].field_ids).toHaveLength(2);
  await expect(grid.getByRole("columnheader")).toHaveCount(2);
  await page.reload();
  await expect(grid.getByRole("columnheader").first()).toContainText(names[2]);
  await expect(grid.getByRole("columnheader")).toHaveCount(2);
  await grid.getByRole("columnheader").first().click({ button: "right" });
  await expect(page.getByRole("menuitem", { name: "编辑列", exact: true })).toBeVisible();
  await expect(page.getByRole("menuitem", { name: "向右插入列", exact: true })).toBeVisible();
  await page.screenshot({ path: test.info().outputPath("column-context-menu.png") });
  await page.keyboard.press("Escape");
  await grid.getByRole("button", { name: `${names[2]}列菜单` }).click();
  await expect(page.getByRole("menuitem", { name: "高亮重复值", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "字段管理", exact: true }).click();
  await manager.getByRole("checkbox", { name: names[1], exact: true }).check();
  await page.screenshot({ path: test.info().outputPath("field-manager.png") });
  await manager.getByRole("button", { name: "应用", exact: true }).click();
  await expect(grid.getByRole("columnheader")).toHaveCount(3);
  await grid.getByRole("button", { name: `${names[2]}列菜单` }).click();
  await page.getByRole("menuitem", { name: "向右插入列", exact: true }).click();
  const fieldEditor = page.getByRole("dialog", { name: "字段设置", exact: true });
  await fieldEditor.getByRole("textbox", { name: "字段名称" }).fill("Inserted");
  await fieldEditor.getByRole("button", { name: "保存字段", exact: true }).click();
  await expect(grid.getByRole("columnheader").nth(1)).toContainText("Inserted");
  await grid.getByRole("button", { name: `${names[0]}列菜单` }).click();
  await page.getByRole("menuitem", { name: "按本列筛选", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "筛选", exact: true }).getByRole("button", { name: /筛选字段 1/ })).toContainText(names[0]);
  await page.getByRole("button", { name: "取消", exact: true }).click();
  await page.getByRole("button", { name: "字段管理", exact: true }).click();
  await manager.getByRole("button", { name: "Inserted字段操作" }).click();
  await manager.getByRole("menuitem", { name: "删除", exact: true }).click();
  await expect(grid.getByRole("columnheader")).toHaveCount(3);
});

test("row gutter, drag ordering and single or multi-record context actions persist", async ({ page, request }) => {
  const { grid, text, records } = await seed(page, request);
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
  const row = (name: string) => grid.locator(".sheet-grid-row").filter({ hasText: name });
  await row("Alpha").hover();
  await expect(row("Alpha").getByRole("button", { name: /查看记录/ })).toBeVisible();
  await drag(page, row("Alpha").getByRole("button", { name: /拖拽记录/ }), row("Gamma"), true);
  await expect.poll(async () => (await records()).map((value: { values: Record<string, string> }) => value.values[text.id])).toEqual(["Beta", "Gamma", "Alpha"]);
  await expect(grid.getByRole("gridcell").first()).toHaveText("Beta");
  await row("Alpha").getByRole("gridcell").first().click({ button: "right" });
  await page.getByRole("menuitem", { name: "复制", exact: false }).filter({ hasText: "Ctrl+C" }).click();
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe("Alpha");
  await page.evaluate(() => navigator.clipboard.writeText("Beta edited"));
  await row("Beta").getByRole("gridcell").first().click({ button: "right" });
  await page.getByRole("menuitem").filter({ hasText: "Ctrl+V" }).click();
  await expect(row("Beta edited")).toBeVisible();
  await row("Alpha").getByRole("gridcell").first().click({ button: "right" });
  await page.getByRole("spinbutton", { name: "向上插入行数" }).fill("2");
  await page.getByRole("menuitem", { name: "向上插入", exact: true }).click();
  await expect.poll(async () => (await records()).length).toBe(5);
  await row("Gamma").getByRole("gridcell").first().click({ button: "right" });
  await page.getByRole("menuitem", { name: "展开行", exact: false }).click();
  await expect(page.getByRole("region", { name: "记录详情", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "收起", exact: true }).click();
  await row("Alpha").getByRole("gridcell").first().click({ button: "right" });
  await page.getByRole("menuitem", { name: "复制行", exact: true }).click();
  await expect.poll(async () => (await records()).filter((value: { values: Record<string, string> }) => value.values[text.id] === "Alpha").length).toBe(2);
  await expect(grid.locator(".sheet-grid-row")).toHaveCount(6);
  await row("Gamma").getByRole("checkbox").check();
  await row("Beta edited").getByRole("checkbox").check();
  await expect(row("Gamma")).toHaveCSS("background-color", "rgb(222, 243, 243)");
  await row("Gamma").getByRole("gridcell").first().click({ button: "right" });
  const menu = page.getByRole("menu", { name: "多选记录操作" });
  await expect(menu.getByRole("menuitem")).toHaveCount(3);
  await page.screenshot({ path: test.info().outputPath("multi-record-context-menu.png") });
  await menu.getByRole("menuitem", { name: "删除行", exact: true }).click();
  await expect.poll(async () => (await records()).length).toBe(4);
  await page.reload();
  await expect(grid.locator(".sheet-grid-row")).toHaveCount(4);
  await expect(grid.getByRole("gridcell").filter({ hasText: "Alpha" })).toHaveCount(2);
});
