import {ownerSession,openWithSession,createCollection,createDocument,workspacePath,sessionHeaders,responseData} from "../helpers/api-fixtures";
import {expect,test} from "@playwright/test";
const apiOrigin=`http://127.0.0.1:${process.env.ORBIS_E2E_API_PORT||"9311"}`;
const password="Orbis-browser-test-2026!";
test("Document writing, comments and anonymous live sharing work through the application",async({page,request,browser})=>{
  const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message));
  const status=await (await request.get(`${apiOrigin}/api/v1/setup`)).json();
  const initialized=Boolean(status.data.initialized);
  await page.goto(initialized?"/login":"/setup");
  if(!initialized)await page.getByLabel("显示名称").fill("Orbis 团队");
  await page.getByLabel("邮箱").fill("owner@example.com");
  await page.getByLabel("密码",{exact:true}).fill(password);
  await page.getByRole("button",{name:initialized?"登录 Orbis":"创建并进入工作空间"}).click();
  await expect(page).toHaveURL(/\/documents$/);
  await page.getByRole("button",{name:"新建笔记本",exact:true}).first().click();
  const dialog=page.getByRole("dialog",{name:"新建笔记本"});
  await dialog.getByLabel("笔记本名称").fill(`Go 验收 ${Date.now()}`);
  await dialog.getByRole("button",{name:/^创建/}).click();
  await expect(page).toHaveURL(/\/collections\/[0-9a-f-]+$/);
  await page.getByRole("region",{name:"主工作区",exact:true}).getByRole("button",{name:"新建文档",exact:true}).click();
  await expect(page).toHaveURL(/\/documents\/[0-9a-f-]+$/);
  const documentId=page.url().split("/").at(-1)!;
  await page.getByRole("textbox",{name:"文档标题"}).fill("Go 原生文档验收");
  const editor=page.locator('[contenteditable="true"]').first();
  await expect(editor).toBeVisible();await editor.fill("经 Go 接口保存的正文。");
  const session=await page.evaluate(()=>JSON.parse(localStorage.getItem("orbis.auth.v2")!));
  const root=`${apiOrigin}/api/v1/workspaces/${session.workspace.id}`;
  const headers={Authorization:`Bearer ${session.accessToken}`};
  await expect.poll(async()=>{
    const response=await request.get(`${root}/documents/${documentId}/content`,{headers});
    const value=(await response.json()).data;
    return {title:value.revision?.title,text:value.blocks?.map((block:{content:Array<{text:string}>})=>block.content.map(run=>run.text).join("")).join("\n")};
  }).toEqual({title:"Go 原生文档验收",text:"经 Go 接口保存的正文。"});
  await page.getByRole("button",{name:"评论与历史",exact:true}).click();
  await page.getByLabel("新评论",{exact:true}).fill("评论也通过工作空间接口保存。");
  await page.getByRole("button",{name:"发表评论",exact:true}).click();
  await expect(page.getByText("评论也通过工作空间接口保存。",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"关闭评论与历史"}).click();
  await page.getByRole("button",{name:"分享",exact:true}).click();
  await page.getByRole("button",{name:"创建公开链接"}).click();
  const link=page.getByRole("textbox",{name:"公开链接",exact:true});await expect(link).toBeVisible();
  const anonymous=await browser.newContext(),reader=await anonymous.newPage();
  const url=await link.inputValue();await reader.goto(url);
  await expect(reader.getByRole("heading",{name:"Go 原生文档验收",exact:true})).toBeVisible();
  await expect(reader.getByText("经 Go 接口保存的正文。",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"撤销链接"}).click();
  await expect(page.getByText("链接已撤销，后续访问立即失效。")).toBeVisible();
  await reader.reload();
  await expect(reader.getByRole("heading",{name:"分享已失效或文档不可访问"})).toBeVisible();
  await anonymous.close();
  await page.getByRole("button",{name:"关闭",exact:true}).click();
  await page.getByRole("link",{name:"Go 原生文档验收",exact:true}).hover();
  await page.getByRole("button",{name:"文档操作 Go 原生文档验收",exact:true}).click();
  await page.getByRole("menuitem",{name:"重命名",exact:true}).click();
  const rename=page.getByRole("dialog",{name:"重命名文档"});
  await rename.getByRole("textbox",{name:"文档标题"}).fill("目录重命名后的标题");
  await rename.getByRole("button",{name:"保存",exact:true}).click();
  await expect(rename).not.toBeVisible();
  await expect(page.getByRole("textbox",{name:"文档标题"})).toHaveValue("目录重命名后的标题");
  await editor.fill("重命名后继续编辑的正文。");
  await expect.poll(async()=>{
    const value=(await(await request.get(`${root}/documents/${documentId}/content`,{headers})).json()).data;
    return {title:value.revision.title,text:value.blocks.map((block:{content:Array<{text:string}>})=>block.content.map(run=>run.text).join("")).join("\n")};
  }).toEqual({title:"目录重命名后的标题",text:"重命名后继续编辑的正文。"});
  expect(errors).toEqual([]);
});

test("Recent document pages and a lost Markdown import response preserve the original intent",async({page,request})=>{
  const session=await ownerSession(request),collection=await createCollection(request,session,`分页与导入 ${Date.now()}`);
  const marker=`最近分页-${Date.now()}`;
  for(let index=0;index<25;index+=1)await createDocument(request,session,collection.id,`${marker}-${index}`);
  await openWithSession(page,session,"/documents/recent");
  await expect(page.getByText(`${marker}-24`,{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"下一页最近文档",exact:true}).click();
  await expect(page.getByText("第 2 页",{exact:true})).toBeVisible();
  await expect(page.getByText(`${marker}-0`,{exact:true})).toBeVisible();
  await expect(page.getByText(`${marker}-24`,{exact:true})).not.toBeVisible();
  await page.goto(`/collections/${collection.id}`);
  const intents:string[]=[];
  await page.route("**/api/v1/workspaces/*/collections/*/imports/markdown",async route=>{
    intents.push(route.request().postData()!);
    if(intents.length===1){const committed=await route.fetch();expect(committed.status()).toBe(201);await route.abort("failed");}
    else await route.continue();
  });
  const listPath=workspacePath(session,`/collections/${collection.id}/documents?page=1&page_size=20`),headers=sessionHeaders(session);
  const before=await responseData(await request.get(listPath,{headers}));
  await page.locator('input[type="file"]').setInputFiles({name:"恢复导入.md",mimeType:"text/markdown",buffer:Buffer.from("# Markdown 重试回执\n\n同一文件只应创建一份文档。")});
  await expect(page.getByText("导入结果尚未确认",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"重试导入",exact:true}).click();
  await expect(page).toHaveURL(/\/documents\/[0-9a-f-]+$/);
  await expect(page.getByText("同一文件只应创建一份文档。",{exact:true})).toBeVisible();
  expect(intents).toHaveLength(2);expect(intents[1]).toBe(intents[0]);
  const after=await responseData(await request.get(listPath,{headers}));
  expect(after.pagination.total).toBe(before.pagination.total+1);
});
