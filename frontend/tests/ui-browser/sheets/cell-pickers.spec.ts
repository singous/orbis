import { expect, test } from "@playwright/test";
import { installSession } from "../fixtures/session";
import { mountTableControl } from "../fixtures/table-controls";

for (const theme of ["light", "dark"] as const) for (const width of [1280, 390]) test.describe(`${theme} cell controls ${width}`, () => {
  test.use({ hasTouch: width === 390 });
  test("keeps IME, option keyboard, UTC+8 calendar, rating and attachment controls", async ({ page }) => {
    await page.setViewportSize({ width, height: 900 });
    await installSession(page);
    await page.addInitScript(theme => localStorage.setItem("orbis.appearance", theme), theme);
    await mountTableControl(page, "sheet-single");
    const search = page.getByRole("textbox", { name: "搜索字段选项", exact: true });
    await expect(search).toBeFocused();
    await search.dispatchEvent("keydown", { key: "Enter", isComposing: true });
    await search.dispatchEvent("keydown", { key: "Escape", isComposing: true });
    await expect(page.getByRole("dialog", { name: "字段选择", exact: true })).toBeVisible();
    await expect(page.getByRole("status", { name: "提交记录" })).toHaveText("[]");
    await expect(page.getByRole("status", { name: "取消次数" })).toHaveText("0");
    await search.press("ArrowDown");
    await page.keyboard.press("ArrowDown");
    await expect(page.getByRole("option", { name: "选项 B", exact: true })).toBeFocused();
    await page.keyboard.press("Space");
    await expect(page.getByRole("dialog")).toHaveCount(0);
    await expect(page.getByRole("status", { name: "当前值" })).toHaveText('"b"');
    await mountTableControl(page, "sheet-multi");
    await page.getByRole("textbox", { name: "搜索字段选项", exact: true }).press("ArrowDown");
    await page.keyboard.press("Space");
    await page.keyboard.press("ArrowDown");
    await page.keyboard.press("Space");
    await expect(page.getByRole("status", { name: "当前值" })).toHaveText('["b"]');
    await page.keyboard.press("Tab");
    await expect(page.getByRole("status", { name: "提交记录" })).toHaveText('[{"navigation":"next"}]');
    await expect(page.getByRole("dialog")).toHaveCount(0);
    await mountTableControl(page, "sheet-time");
    await page.getByRole("button", { name: "下个月", exact: true }).click();
    await expect(page.getByRole("dialog")).toContainText("2026 年 11 月");
    await page.getByRole("button", { name: "上个月", exact: true }).click();
    await page.getByLabel("时间", { exact: true }).fill("09:45");
    await page.getByRole("button", { name: "2026-10-10", exact: true }).focus();
    await page.keyboard.press("Enter");
    await expect(page.getByRole("status", { name: "当前值" })).toHaveText(String(Date.parse("2026-10-10T09:45:00+08:00")));
    await mountTableControl(page, "checkbox");
    const checkbox = page.getByRole("checkbox", { name: "字段", exact: true });
    await expect(checkbox).toHaveCSS("width", "16px");
    await checkbox.focus();
    await page.keyboard.press("Space");
    await expect(page.getByRole("status", { name: "当前值" })).toHaveText("true");
    await mountTableControl(page, "radio");
    const radio = page.getByRole("radio", { name: "选项 A", exact: true });
    await expect(radio).toHaveCSS("width", "16px");
    await expect(radio).toBeChecked();
    await radio.focus();
    await page.keyboard.press("ArrowDown");
    await expect(page.getByRole("status", { name: "当前值" })).toHaveText('"b"');
    await mountTableControl(page, "rating");
    await page.emulateMedia({ forcedColors: "active", reducedMotion: "reduce" });
    const star = page.getByRole("button", { name: "4 星", exact: true });
    await star.focus();
    await page.keyboard.press("Space");
    await expect(page.getByRole("status", { name: "当前值" })).toHaveText("4");
    await page.keyboard.press("Space");
    await expect(page.getByRole("status", { name: "当前值" })).toHaveText("null");
    await expect(star).toHaveCSS("outline-width", "2px");
    await page.route("**/api/v1/**", async route => {
      if (new URL(route.request().url()).pathname.endsWith("/content")) await route.fulfill({ body: "fixture attachment", contentType: "application/pdf" });
      else await route.fulfill({ json: { code: "OK", message: "", request_id: "cell-picker", data: { filename: "资料.pdf", size_bytes: 100 } } });
    });
    await mountTableControl(page, "attachment");
    const attachment = page.getByRole("button", { name: "资料.pdf", exact: true });
    await expect(attachment).toBeVisible();
    const download = page.waitForEvent("download");
    await attachment.click();
    expect((await download).suggestedFilename()).toBe("资料.pdf");
    await page.getByRole("button", { name: "移除附件", exact: true }).focus();
    await page.keyboard.press("Space");
    await expect(page.getByRole("status", { name: "当前值" })).toHaveText("[]");
    await expect(attachment).toHaveCount(0);
    await expect(page.getByRole("status", { name: "提交记录" })).toHaveText("[]");
  });
});
