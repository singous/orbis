import { fireEvent, render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { createRef } from "react";
import { expect, it, vi } from "vitest";
import { Button } from "./Button";
import { ActionButton } from "./ActionButton";
import { IconButton } from "./IconButton";
import { TextInput } from "./TextInput";
import { SelectField } from "./SelectField";

it("preserves both activation APIs exactly once and records keyboard/virtual source", async () => {
  const onPress = vi.fn(), onClick = vi.fn();
  const user = userEvent.setup();
  render(<ActionButton onPress={onPress} onClick={onClick}>连接</ActionButton>);
  const button = screen.getByRole("button", { name: "连接" });
  await user.click(button);
  expect(onPress.mock.calls[0][0].pointerType).toBe("mouse");
  await user.keyboard("{Enter}");
  expect(onPress.mock.calls[1][0].pointerType).toBe("keyboard");
  await user.keyboard(" ");
  expect(onPress.mock.calls[2][0].pointerType).toBe("keyboard");
  fireEvent.click(button);
  expect(onPress.mock.calls[3][0].pointerType).toBe("virtual");
  expect(onPress).toHaveBeenCalledTimes(4);
  expect(onClick).toHaveBeenCalledTimes(4);
});
it("preserves old native pending semantics and low-level role/ref/content DOM", async () => {
  const ref = createRef<HTMLButtonElement>(), action = vi.fn();
  const user = userEvent.setup();
  render(<><Button isPending onPress={action}>保存</Button><ActionButton ref={ref} role="tab" aria-selected contentEditable={false} title="说明"><svg data-testid="icon" />源代码</ActionButton><IconButton aria-label="操作" isDisabled onPress={action}>…</IconButton></>);
  const pending = screen.getByRole("button", { name: "保存" });
  expect(pending).toBeDisabled();
  expect(pending).toHaveAttribute("aria-busy", "true");
  expect(pending).not.toHaveAttribute("aria-labelledby");
  await user.click(pending);
  await user.click(screen.getByRole("button", { name: "操作" }));
  expect(action).not.toHaveBeenCalled();
  expect(ref.current).toBe(screen.getByRole("tab"));
  expect(ref.current?.firstElementChild).toBe(screen.getByTestId("icon"));
  expect(ref.current).toHaveAttribute("contenteditable", "false");
  expect(ref.current).toHaveAttribute("aria-selected", "true");
});
it("keeps labeled text fields and empty string options as real values", async () => {
  const change = vi.fn();
  const user = userEvent.setup();
  render(<><TextInput label="名称" defaultValue="原名称" /><SelectField label="分组" value="name" options={[{ value: "", label: "不分组" }, { value: "name", label: "按名称" }]} onChange={change} /></>);
  await user.clear(screen.getByRole("textbox", { name: "名称" }));
  await user.type(screen.getByRole("textbox", { name: "名称" }), "新名称");
  await user.click(screen.getByRole("combobox", { name: "分组" }));
  await user.click(await screen.findByRole("option", { name: "不分组" }));
  expect(change).toHaveBeenCalledWith("");
});
