import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { cleanup, renderHook, waitFor } from "@testing-library/react";
import { StrictMode, type ReactNode } from "react";
import { afterEach, expect, it, vi } from "vitest";
import { useSheet } from "./use-sheet";
const notify = vi.hoisted(() => vi.fn());
vi.mock("../../shared/ui/Toast", () => ({ showToast: notify }));
vi.mock("../../shared/auth/use-auth-request", () => ({ useAuthRequest: () => ({ workspaceId: "space", accessToken: "token" }) }));
const api = { get: async () => ({ definition: { fields: [], views: [] }, version: 1, data_revision: 1 }), forms: async () => [], records: vi.fn(), stats: vi.fn() };
vi.mock("./api", () => ({ sheetAPI: () => api }));
afterEach(() => { cleanup(); sessionStorage.clear(); notify.mockClear(); });
it("reports an unreadable local draft once under StrictMode while keeping it intact", async () => {
  const key = "orbis.sheet-draft:undefined:space:sheet";
  sessionStorage.setItem(key, "{incomplete");
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const wrapper = ({ children }: { children: ReactNode }) => <StrictMode><QueryClientProvider client={client}>{children}</QueryClientProvider></StrictMode>;
  renderHook(() => useSheet("sheet", "", ""), { wrapper });
  await waitFor(() => expect(notify).toHaveBeenCalledExactlyOnceWith({ title: "无法读取本机草稿。", tone: "danger" }));
  expect(sessionStorage.getItem(key)).toBe("{incomplete");
  client.clear();
});
