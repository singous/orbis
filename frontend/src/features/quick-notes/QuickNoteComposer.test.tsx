import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { ApiError } from "../../shared/api/api-client";
import type { NativeBlock } from "../content/codecs/api-content";
import * as drafts from "./draft";
import { QuickNoteComposer } from "./QuickNoteComposer";
const mocks = vi.hoisted(() => ({ save: vi.fn(), notify: vi.fn() }));
vi.mock("./api", () => ({ saveQuickNote: mocks.save }));
vi.mock("../../shared/ui/Toast", () => ({ showToast: mocks.notify }));
vi.mock("../../shared/auth/use-auth-request", () => ({ useAuthRequest: () => ({ accessToken: "a", workspaceId: "space" }) }));
vi.mock("./QuickNoteEditor", () => ({ QuickNoteEditor: ({ onChange, onSubmit }: { onChange: (blocks: NativeBlock[]) => void; onSubmit: () => void }) => <textarea aria-label="随手记正文" onChange={event => onChange([{ id: "00000000-0000-4000-8000-000000000001", type: "paragraph", props: {}, children: [], content: [{ text: event.target.value, marks: [], href: null }] }])} onKeyDown={event => { if (event.ctrlKey && event.key === "Enter") onSubmit(); }} /> }));
const props = { userId: "user", workspaceId: "space", tags: [], canEdit: true, onSaved: vi.fn(), onManageTags: vi.fn() };
beforeEach(() => { localStorage.clear(); mocks.save.mockReset(); mocks.notify.mockClear(); });
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it("announces one storage failure per failed period and resets after storage recovers", () => {
  const write = vi.spyOn(drafts, "writeDraft").mockReturnValue(false);
  render(<QuickNoteComposer {...props} />);
  const editor = screen.getByRole("textbox", { name: "随手记正文" });
  fireEvent.change(editor, { target: { value: "保留" } });
  fireEvent.change(editor, { target: { value: "保留内容" } });
  expect(mocks.notify).toHaveBeenCalledExactlyOnceWith({ title: "本机草稿保存失败，请保留页面并提交记录", tone: "danger" });
  write.mockReturnValue(true);
  fireEvent.change(editor, { target: { value: "恢复存储" } });
  write.mockReturnValue(false);
  fireEvent.change(editor, { target: { value: "再次失败" } });
  expect(mocks.notify).toHaveBeenCalledTimes(2);
  expect(editor).toHaveValue("再次失败");
});
it("uses the same save-as-new operation for the conflict button and keyboard shortcut", async () => {
  const note = { id: crypto.randomUUID(), workspace_id: crypto.randomUUID(), owner_id: crypto.randomUUID(), version: 3, blocks: [], tag_ids: [], is_pinned: false, created_at_ms: 1, updated_at_ms: 1, deleted_at_ms: null };
  mocks.save.mockRejectedValueOnce(new ApiError(409, "记录已被修改", "QUICK_NOTE_VERSION_CONFLICT")).mockResolvedValueOnce(note);
  render(<QuickNoteComposer {...props} note={note} />);
  const editor = screen.getByRole("textbox", { name: "随手记正文" });
  fireEvent.change(editor, { target: { value: "冲突后保留的内容" } });
  fireEvent.click(screen.getByRole("button", { name: "保存修改" }));
  await screen.findByRole("button", { name: "将当前内容另存为新记录" });
  fireEvent.keyDown(editor, { ctrlKey: true, key: "Enter" });
  await waitFor(() => expect(mocks.save).toHaveBeenCalledTimes(2));
  expect(mocks.save.mock.calls[0][1]).toBe(note.id);
  expect(mocks.save.mock.calls[1][1]).toBeNull();
  expect(mocks.save.mock.calls[1][2]).toMatchObject({ expected_version: 0, blocks: [{ content: [{ text: "冲突后保留的内容" }] }] });
});
