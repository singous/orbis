import { expect, test } from "@playwright/test";

test.use({ screenshot: "off", trace: "off" });

test("rail navigation, creation dialog and global search share real workspace resources", async ({ page, request }) => {
  const credentials = { email: "owner@example.com", password: "Orbis-browser-test-2026!" };
  const setup = await request.post("/api/setup", { data: { ...credentials, display_name: "Search acceptance" } });
  expect([201, 409]).toContain(setup.status());
  const auth = (await (await request.post("/api/auth/login", { data: credentials })).json()).data;
  const headers = { Authorization: `Bearer ${auth.access_token}` };
  const keyword = `搜索验收${Date.now()}`;
  const notebookResponse = await request.post("/api/notebooks", { headers, data: { title: `${keyword}笔记本` } });
  expect(notebookResponse.status()).toBe(201);
  const notebook = (await notebookResponse.json()).data;
  const noteResponse = await request.post("/api/notes", { headers, data: { notebook_id: notebook.id, title: `${keyword}文档` } });
  expect(noteResponse.status()).toBe(201);
  const note = (await noteResponse.json()).data;
  await page.goto("/login");
  await page.getByLabel("邮箱", { exact: true }).fill(credentials.email);
  await page.getByLabel("密码", { exact: true }).fill(credentials.password);
  await page.getByRole("button", { name: "登录 Orbis", exact: true }).click();
  await expect(page).toHaveURL(/\/documents$/);
  const rail = page.getByRole("complementary", { name: "应用导航" });
  const order = await rail.locator("button, a").evaluateAll(items => items.map(item => item.getAttribute("aria-label")));
  expect(order.indexOf("搜索")).toBeGreaterThan(order.indexOf("新建资产"));
  expect(order.indexOf("搜索")).toBeLessThan(order.indexOf("首页"));
  await rail.getByRole("link", { name: "在线文档", exact: true }).hover();
  await expect(page.getByRole("navigation", { name: "笔记本快捷访问" })).toHaveCount(0);
  await expect(page.getByRole("navigation", { name: "文档导航", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "收起侧栏", exact: true }).click();
  await rail.getByRole("link", { name: "在线文档", exact: true }).click();
  await expect(page.getByRole("navigation", { name: "文档导航", exact: true })).toBeVisible();
  await rail.getByRole("button", { name: "新建资产", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "新建资产", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(rail.getByRole("button", { name: "新建资产", exact: true })).toBeFocused();
  await rail.getByRole("button", { name: "搜索", exact: true }).click();
  await expect(page).toHaveURL(/\/documents$/);
  const palette = page.getByRole("dialog", { name: "全局搜索", exact: true });
  await palette.getByRole("combobox", { name: "搜索任何内容", exact: true }).fill(keyword);
  await expect(palette.locator("[data-search-result]")).toHaveCount(2);
  await expect(palette.locator(`[data-search-result][href="/documents/${note.id}"]`)).toBeVisible();
  await expect(palette.locator(`[data-search-result][href="/collections/${notebook.id}"]`)).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(palette).toHaveCount(0);
  await page.goto(`/documents/search?q=${encodeURIComponent(keyword)}&status=active`);
  await expect(page).toHaveURL(/\/search\?.*type=document/);
  await expect(page.locator(".global-search-result-heading h2")).toHaveText([`${keyword}文档`]);
  expect((await request.post(`/api/notes/${note.id}/archive`, { headers })).status()).toBe(200);
  await page.goto(`/search?q=${encodeURIComponent(keyword)}&type=document&status=archived`);
  await page.locator(".global-search-result").click();
  await expect(page).toHaveURL(new RegExp(`/documents/archive\\?resource=${note.id}&type=document`));
  const focusedArchive = page.locator('[aria-label="搜索定位的归档内容"]');
  await expect(focusedArchive).toContainText(`${keyword}文档`);
  await expect(focusedArchive).toBeFocused();
  await expect(page.getByText(`${keyword}文档`, { exact: true })).toHaveCount(1);
  await focusedArchive.getByRole("button", { name: `恢复 ${keyword}文档`, exact: true }).click();
  await expect(page.getByText("该内容已不在归档中", { exact: true })).toBeVisible();
  expect((await request.get(`/api/notes/${note.id}`, { headers })).status()).toBe(200);
});
